// Study all cards: a practice run through every card in a deck (and its
// subdecks), shuffled, as if they were all new, until each is answered right.
// It's for grinding before a test, so it leaves the real schedule and review
// history alone: nothing here is saved.

import { useCallback, useEffect, useMemo, useState } from 'react';
import type { View } from '../App';
import { useCollection } from '../lib/collection';
import { isWithin } from '../lib/deckTree';
import { renderMedia } from '../lib/media';
import type { Card, Id } from '../lib/types';

/** How many cards later a card comes back, by answer. */
const AGAIN_GAP = 3;
const HARD_GAP = 8;

function shuffle<T>(list: T[]): T[] {
  const a = [...list];
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

export function Cram({ deckId, go }: { deckId: Id; go: (v: View) => void }) {
  const col = useCollection();
  const deck = col.decks.get(deckId);

  /** every card in the deck tree, except suspended ones and smart cards (whose
   * versions are generated by the regular reviewer) */
  const all = useMemo(() => {
    if (!deck) return [];
    const names = new Map([...col.decks.values()].map((d) => [d.id, d.name]));
    return [...col.cards.values()].filter((c) => {
      if (c.queue === -1 || !isWithin(names.get(c.deckId) ?? '', deck.name)) return false;
      const note = c.noteId !== undefined ? col.notes.get(c.noteId) : undefined;
      return note?.kind !== 'smart';
    });
    // only the cards present when the session starts
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [deckId]);

  const [queue, setQueue] = useState<Id[]>(() => shuffle(all.map((c) => c.id)));
  const [done, setDone] = useState(0);
  const [missed, setMissed] = useState(0);
  const [showAnswer, setShowAnswer] = useState(false);
  const card: Card | undefined = queue.length ? col.cards.get(queue[0]) : undefined;

  const restart = () => {
    setQueue(shuffle(all.map((c) => c.id)));
    setDone(0);
    setMissed(0);
    setShowAnswer(false);
  };

  /** again/hard put the card back a few cards later; good/easy finish it */
  const answer = useCallback(
    (gap: number | null) => {
      if (!showAnswer) return;
      setQueue((q) => {
        const [first, ...rest] = q;
        if (gap === null) return rest;
        const at = Math.min(gap, rest.length);
        return [...rest.slice(0, at), first, ...rest.slice(at)];
      });
      if (gap === null) setDone((n) => n + 1);
      if (gap === AGAIN_GAP) setMissed((n) => n + 1);
      setShowAnswer(false);
    },
    [showAnswer],
  );

  useEffect(() => {
    const onKey = (e: KeyboardEvent) => {
      if (e.target instanceof HTMLInputElement || e.target instanceof HTMLTextAreaElement) return;
      if (!card) return;
      if (!showAnswer && (e.key === ' ' || e.key === 'Enter')) {
        e.preventDefault();
        setShowAnswer(true);
      } else if (showAnswer && (e.key === ' ' || e.key === 'Enter' || e.key === '3' || e.key === '4')) {
        e.preventDefault();
        answer(null);
      } else if (showAnswer && e.key === '1') answer(AGAIN_GAP);
      else if (showAnswer && e.key === '2') answer(HARD_GAP);
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [card, showAnswer, answer]);

  if (!deck) return <div className="panel">Deck not found.</div>;
  const title = deck.name.split('::').join(' › ');

  if (!all.length) {
    return (
      <div className="panel" style={{ textAlign: 'center', padding: 48 }}>
        <h1>No cards to study in “{title}”.</h1>
        <div className="row" style={{ justifyContent: 'center', marginTop: 16 }}>
          <button onClick={() => go({ name: 'add', deckId })}>Add cards</button>
          <button onClick={() => go({ name: 'decks' })}>Back to Home</button>
        </div>
      </div>
    );
  }

  if (!card) {
    return (
      <div className="panel" style={{ textAlign: 'center', padding: 48 }}>
        <h1>You got through all {all.length} cards!</h1>
        <p className="muted">
          {missed === 0 ? 'Every one right the first time.' : `${missed} miss${missed === 1 ? '' : 'es'} along the way.`} Your regular schedule wasn't changed.
        </p>
        <div className="row" style={{ justifyContent: 'center', marginTop: 16 }}>
          <button className="primary" onClick={restart}>
            Go again
          </button>
          <button onClick={() => go({ name: 'decks' })}>Back to Home</button>
        </div>
      </div>
    );
  }

  const left = queue.length;
  return (
    <div className="reviewer">
      <div className="row">
        <button className="link" onClick={() => go({ name: 'decks' })}>
          ← Home
        </button>
        <strong>{title}</strong>
        <span className="muted">· Studying all cards</span>
        <span className="spacer" />
        <span className="muted num" title="Practice only: your regular schedule isn't changed">
          {done} of {all.length} done
        </span>
        <button onClick={restart} title="Shuffle and start over">
          Restart
        </button>
      </div>

      <div className="cram-progress" aria-hidden="true">
        <span style={{ width: `${(done / all.length) * 100}%` }} />
      </div>

      <div className="panel card-face">
        {showAnswer && card.answerReplacesFront ? (
          <div className="answer-part" dangerouslySetInnerHTML={{ __html: renderMedia(card.back) }} />
        ) : (
          <>
            <div dangerouslySetInnerHTML={{ __html: renderMedia(card.front) }} />
            {showAnswer && (
              <>
                <hr />
                <div className="answer-part" dangerouslySetInnerHTML={{ __html: renderMedia(card.back) }} />
              </>
            )}
          </>
        )}
      </div>

      {showAnswer ? (
        <div className="answer-bar">
          <button className="again" onClick={() => answer(AGAIN_GAP)}>
            <span className="ivl">Soon</span>
            <strong>Again</strong>
            <span className="kbd">1</span>
          </button>
          <button className="hard" onClick={() => answer(HARD_GAP)}>
            <span className="ivl">Later</span>
            <strong>Hard</strong>
            <span className="kbd">2</span>
          </button>
          <button className="good" onClick={() => answer(null)}>
            <span className="ivl">Done</span>
            <strong>Good</strong>
            <span className="kbd">3</span>
          </button>
        </div>
      ) : (
        <button
          className="primary show-answer"
          onClick={(e) => {
            e.currentTarget.blur();
            setShowAnswer(true);
          }}
        >
          Show answer <span style={{ opacity: 0.7, fontSize: 12 }}>(Space)</span>
        </button>
      )}
      <p className="muted" style={{ textAlign: 'center', fontSize: 13, margin: 0 }}>
        {left} card{left === 1 ? '' : 's'} left · practice only, your regular schedule isn't changed
      </p>
    </div>
  );
}
